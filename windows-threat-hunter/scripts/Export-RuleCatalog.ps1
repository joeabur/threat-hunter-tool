#Requires -Version 5.1
<#
.SYNOPSIS
    Generates docs/rule-catalog.md from the shipped rule files, so the documentation cannot drift from the rules.

.PARAMETER Check
    Do not write; exit 1 if docs/rule-catalog.md differs from what would be generated.

.EXAMPLE
    ./scripts/Export-RuleCatalog.ps1
#>
[CmdletBinding()]
param([switch]$Check)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Import-Module (Join-Path (Join-Path (Join-Path (Join-Path $root 'src') 'Modules') 'WindowsThreatHunter') 'WindowsThreatHunter.psd1') -Force

function ConvertTo-MdCell([string]$Text) { return ($Text -replace '\|', '\|' -replace '[\r\n]+', ' ') }

$rules = @(Get-WthRule -Full | Sort-Object id)
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('# Rule catalog')
[void]$sb.AppendLine()
[void]$sb.AppendLine('<!-- Generated by scripts/Export-RuleCatalog.ps1. Do not edit by hand. -->')
[void]$sb.AppendLine()
[void]$sb.AppendLine("This catalog lists all $($rules.Count) shipped rules. Severity and confidence are separate: severity is the impact if the finding is real, confidence is how likely it is to be real given the evidence the rule uses.")
[void]$sb.AppendLine()
[void]$sb.AppendLine('| Rule | Name | Severity | Confidence | Data source | ATT&CK | Enabled |')
[void]$sb.AppendLine('|---|---|---|---|---|---|---|')
foreach ($r in $rules) {
    $att = (@($r.attack) | Where-Object { $_ } | ForEach-Object { if ($_ -is [string]) { $_ } else { $_.id } }) -join ', '
    if (-not $att) { $att = 'none' }
    $enabled = if ($r.PSObject.Properties.Name -contains 'enabled' -and -not $r.enabled) { 'no (opt-in)' } else { 'yes' }
    [void]$sb.AppendLine("| [$($r.id)](#$($r.id.ToLowerInvariant())) | $(ConvertTo-MdCell $r.name) | $($r.severity) | $($r.confidence) | $($r.dataSource) | $att | $enabled |")
}
foreach ($r in $rules) {
    [void]$sb.AppendLine()
    [void]$sb.AppendLine("## $($r.id)")
    [void]$sb.AppendLine()
    [void]$sb.AppendLine("**$($r.name)** (version $($r.version), category $($r.category))")
    [void]$sb.AppendLine()
    [void]$sb.AppendLine($r.description)
    [void]$sb.AppendLine()
    [void]$sb.AppendLine("- Rationale: $($r.rationale)")
    [void]$sb.AppendLine("- Evidence required: $(@($r.evidenceRequirements) -join '; ')")
    [void]$sb.AppendLine("- Likely false positives: $(@($r.falsePositives) -join '; ')")
    [void]$sb.AppendLine("- Next step: $($r.remediation)")
}
$text = $sb.ToString().Replace("`r`n", "`n")
$target = Join-Path (Join-Path $root 'docs') 'rule-catalog.md'
if ($Check) {
    $current = if (Test-Path -LiteralPath $target) { [System.IO.File]::ReadAllText($target).Replace("`r`n", "`n") } else { '' }
    if ($current -ne $text) { Write-Output 'docs/rule-catalog.md is out of date. Run scripts/Export-RuleCatalog.ps1.'; exit 1 }
    Write-Output 'docs/rule-catalog.md is up to date.'
    exit 0
}
[void][System.IO.Directory]::CreateDirectory((Split-Path -Parent $target))
[System.IO.File]::WriteAllText($target, $text, (New-Object System.Text.UTF8Encoding($false)))
Write-Output "Wrote $target"
