#!/usr/bin/env python3
"""Generate docs/detection-coverage.md from the shipped rules (so docs cannot drift)."""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from mac_threat_hunter.attack import resolve  # noqa: E402
from mac_threat_hunter.config import default_rules_dir, load_config  # noqa: E402
from mac_threat_hunter.rules_engine.loader import load_rules  # noqa: E402

HEADER = """# Detection coverage

This file is generated by `python scripts/gen_coverage.py` from the rules in `rules/`; a test
fails if it is out of date. Do not edit it by hand.

**How to read it.** A *detection rule* describes observable behaviour in telemetry. An *ATT&CK
technique* is a name for an adversary behaviour. A rule is mapped to a technique only when the
behaviour it looks for is an instance of that technique; a mapping never means the technique was
used, and unmapped rules are not less important. Techniques not listed here are **not covered**,
which is not the same as "absent" on your hosts. The tool does not claim complete ATT&CK
coverage, does not detect all macOS malware, and is not an EDR replacement.

Class: `heuristic` = rule inference needing validation; `ioc_match` = hit on an analyst-supplied
indicator; `baseline_change` = observed difference from a baseline (significance unknown).

"""

FOOTER = """
## Known gaps

- No process-injection, kernel-extension, TCC/privacy-database, XPC, DMG/installer or browser
  extension telemetry; no file-write or process-exec event stream (collection is a point-in-time
  snapshot, so short-lived processes are missed).
- Login Items (Background Task Management) are not collected; only LaunchAgents/Daemons, startup
  items, shell startup files, login/logout hooks and the current user's crontab are.
- Network visibility is limited to `lsof` snapshots; unprivileged runs see only the caller's own
  sockets. No DNS, proxy or packet data. Domain IOCs match only when a hostname is present in the
  evidence (for example a log line or command line).
- Unified-log rules only see records inside the queried window and predicate; macOS redacts
  `<private>` fields and this tool cannot recover them.
- Code-signing context is `codesign -dv` metadata only; signatures are not cryptographically
  verified, and notarisation/Gatekeeper assessment is not performed.
- Rules are heuristics with documented false positives; tune allowlists in
  `configs/allowlists.yaml` for your fleet.
"""


def main() -> str:
    cfg = load_config()
    rs = load_rules([default_rules_dir()], cfg)
    assert rs.ok
    lines = [HEADER, f"{len(rs.rules)} rules ship with this version.\n"]
    lines.append("| Rule | Name | Class | Source | Severity / confidence | ATT&CK |")
    lines.append("|---|---|---|---|---|---|")
    for r in rs.rules:
        tech = (
            ", ".join(
                f"[{t} {resolve(t).name}]({resolve(t).url})"
                for t in r.techniques  # type: ignore[union-attr]
            )
            or "none"
        )
        lines.append(
            f"| `{r.id}` v{r.version} | {r.name} | {r.category} | {', '.join(r.sources)} | "
            f"{r.severity} / {r.confidence} | {tech} |"
        )
    lines.append("\n## Per-rule notes\n")
    for r in rs.rules:
        lines.append(f"### {r.id}: {r.name}\n")
        lines.append(f"{r.rationale}\n")
        if r.attack_justification:
            lines.append(f"*Mapping justification:* {r.attack_justification}\n")
        lines.append("Known false positives:\n")
        lines += [f"- {x}" for x in r.false_positives]
        lines.append("")
    lines.append(FOOTER)
    return "\n".join(lines)


if __name__ == "__main__":
    (ROOT / "docs" / "detection-coverage.md").write_text(main(), encoding="utf-8")
    print("wrote docs/detection-coverage.md")
